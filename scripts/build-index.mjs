#!/usr/bin/env node
/**
 * build-index.mjs — overlay radar runtime verdicts onto a format-1 market index.
 *
 * The radar knows whether a repo actually runs, but not how to install it; a market
 * index (awesome-dsh-plugin's dsh-plugin-catalog by default) knows how to install it,
 * but only what the author declared in `engines.dsh`. This joins the two by GitHub
 * repository and adds `radar-*` labels plus a `stars` sort key, so the DSH Discover
 * tab can filter by measured compatibility with no plugin installed.
 *
 * Nothing is dropped from the base index; unmatched plugins are left unlabelled.
 *
 * Usage: node scripts/build-index.mjs [--base <url|file>] [--radar <url|file>] [--out index.json]
 */
import { rename, writeFile } from 'node:fs/promises'
import { RADAR_LABELS, RADAR_SORT_KEYS, RADAR_SOURCES, loadJson, radarMap, repoKey } from '../lib/radar.js'

export const DEFAULT_BASE = [
  'https://cdn.jsdelivr.net/npm/dsh-plugin-catalog/index.json',
  'https://awesome-dsh-plugin.com/index.json',
]

/** Pure overlay; `baseUrl` resolves the base index's relative icon references before re-hosting. */
export function overlay(base, pluginsAll, baseUrl) {
  if (!base || base.format !== 1 || !Array.isArray(base.plugins)) throw new Error('base: not a format-1 index')
  const radar = radarMap(pluginsAll)
  const meta = base.metadata ?? {}
  for (const id of Object.keys(RADAR_LABELS)) {
    if (meta.labels?.[id]) throw new Error(`base already declares label ${id}`)
  }
  let matched = 0
  const plugins = base.plugins.map((p) => {
    const out = { ...p, metadata: { ...(p.metadata ?? {}) } }
    if (out.icon && !/^(data:|https?:)/.test(out.icon) && /^https?:/.test(baseUrl ?? '')) {
      out.icon = new URL(out.icon, baseUrl).href
    }
    const hit = radar.get(repoKey(p.repository?.url))
    if (hit) {
      matched++
      out.metadata.labels = [...(out.metadata.labels ?? []), hit.label]
      if (hit.stars !== undefined) out.metadata.sortKeys = { ...(out.metadata.sortKeys ?? {}), stars: hit.stars }
    }
    return out
  })
  const zh = base.title?.zh ?? base.title?.en ?? '插件市场'
  const en = base.title?.en ?? base.title?.zh ?? 'Plugin market'
  return {
    index: {
      format: 1,
      title: { zh: `${zh} · 雷达实测`, en: `${en} · Radar verified` },
      description: {
        zh: `在「${zh}」上叠加 DSH 插件雷达的运行级实测判定（标签：雷达实测通过/不兼容/待测）。由 dsh-autofit 生成。`,
        en: `${en} with DSH Plugin Radar runtime verdicts as labels. Generated by dsh-autofit.`,
      },
      metadata: {
        categories: meta.categories ?? {},
        labels: { ...(meta.labels ?? {}), ...RADAR_LABELS },
        sortKeys: { ...(meta.sortKeys ?? {}), ...RADAR_SORT_KEYS },
      },
      plugins,
    },
    stats: { plugins: plugins.length, matched },
  }
}

function arg(name, fallback) {
  const i = process.argv.indexOf(name)
  return i > 0 && process.argv[i + 1] ? [process.argv[i + 1]] : fallback
}

async function main() {
  const out = arg('--out', ['index.json'])[0]
  const base = await loadJson(arg('--base', DEFAULT_BASE))
  const radar = await loadJson(arg('--radar', RADAR_SOURCES))
  const { index, stats } = overlay(base.value, radar.value, base.url)
  const tmp = `${out}.tmp`
  await writeFile(tmp, JSON.stringify(index) + '\n')
  await rename(tmp, out)
  const by = {}
  for (const p of index.plugins) for (const l of p.metadata.labels ?? []) if (l.startsWith('radar-')) by[l] = (by[l] ?? 0) + 1
  console.log(`[autofit] ${out}: ${stats.plugins} plugins, ${stats.matched} radar-matched`, by)
  console.log(`[autofit] base=${base.url} radar=${radar.url} radar_generated_at=${radar.value.generated_at}`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error(`[autofit] ${err.message}`)
    process.exit(1)
  })
}
